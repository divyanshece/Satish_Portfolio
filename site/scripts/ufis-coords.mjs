#!/usr/bin/env node
/**
 * Writes src/styles/ufis-coords.css from src/lib/ufis-layout.mjs.
 *
 * Two kinds of rule come out of it:
 *
 *   1. Geometry — every HTML piece of the illustration is placed on the
 *      1200 × 800 board with percentage boxes, so the figure scales as one
 *      drawing. Groups (the slide's little compositions — a phone with its
 *      screen, the social icons on a handset) keep the member coordinates
 *      that were measured off the slide; those rules are carried over from
 *      the previous sheet untouched.
 *
 *   2. Timing — the bead's window on every channel is computed from the
 *      path's length and the bead's speed, so parallel streams arrive
 *      together; ripples open when a bead leaves or arrives; each panel
 *      fills while the pulse is inside it. All of it is keyframes and
 *      custom properties keyed to fractions of one loop.
 *
 * Run after any change to the layout module:  node scripts/ufis-coords.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BOARD, TILES, GROUPS, TEXTS, CHANNELS, RETURN, RIPPLES, FOCUS, SPEED, LOOP } from "../src/lib/ufis-layout.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../src/styles/ufis-coords.css");

const MEMBERS = [
  "phone-frame", "app-shot-a", "varshamitra",
  "phone-black", "facebook", "bluesky", "x", "whatsapp", "linkedin",
  "ai-network", "book-gears", "ai-head",
  "phone-frame-2", "app-shot-a-2", "phone-frame-3", "app-shot-b",
  "telegram", "whatsapp-2", "alert-phone",
];

const pct = (v, base) => `${+((v / base) * 100).toFixed(3)}%`;
const px = (v) => pct(v, BOARD.w);
const py = (v) => pct(v, BOARD.h);
const f = (v) => +v.toFixed(3);

// ---- Geometry: member rules measured off the slide, kept verbatim ----------
const previous = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
const kept = MEMBERS.map((k) => {
  const m = previous.match(new RegExp(`^\\.ufis \\.k-${k.replace(/-/g, "\\-")}\\{[^\\n]*\\}$`, "m"));
  if (!m) throw new Error(`ufis-coords: no carried-over rule for group member "${k}" in ${out}`);
  return m[0];
});

// ---- Timing: path lengths -------------------------------------------------
function pathLength(d) {
  const toks = d.match(/[A-Za-z]|-?\d+(?:\.\d+)?/g);
  let cmd = null, x = 0, y = 0, len = 0, i = 0;
  const num = () => +toks[i++];
  while (i < toks.length) {
    if (/[A-Za-z]/.test(toks[i])) { cmd = toks[i++]; continue; }
    if (cmd === "M") { x = num(); y = num(); }
    else if (cmd === "L") { const nx = num(), ny = num(); len += Math.hypot(nx - x, ny - y); x = nx; y = ny; }
    else if (cmd === "H") { const nx = num(); len += Math.abs(nx - x); x = nx; }
    else if (cmd === "V") { const ny = num(); len += Math.abs(ny - y); y = ny; }
    else if (cmd === "C") {
      const [x1, y1, x2, y2, x3, y3] = [num(), num(), num(), num(), num(), num()];
      let px0 = x, py0 = y;
      for (let s = 1; s <= 48; s++) {
        const t = s / 48, u = 1 - t;
        const bx = u * u * u * x + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t * t * t * x3;
        const by = u * u * u * y + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t * t * t * y3;
        len += Math.hypot(bx - px0, by - py0); px0 = bx; py0 = by;
      }
      x = x3; y = y3;
    } else throw new Error(`ufis-coords: unhandled path command ${cmd}`);
  }
  return len;
}

const channels = [...CHANNELS, RETURN].map((c) => {
  const len = pathLength(c.d);
  const dur = len / (SPEED * LOOP);
  return { ...c, len, start: f(c.arrive - dur), end: f(c.arrive) };
});
const byId = Object.fromEntries(channels.map((c) => [c.id, c]));

// The bead is a zero-length dash with round caps: a dot. Parked just before
// the start (offset .12) it is off the path; carried to −1.2 it is past the end.
const cometFrames = (id, a, b) =>
  `@keyframes ufis-cm-${id}{0%,${f(a * 100)}%{stroke-dashoffset:.12}${f(b * 100)}%{stroke-dashoffset:-1.2}100%{stroke-dashoffset:-1.2}}`;

// ---- Emit ---------------------------------------------------------------
const lines = [
  "/* Generated by scripts/ufis-coords.mjs from src/lib/ufis-layout.mjs — do not edit by hand.",
  `   Boxes are percentages of the ${BOARD.w} × ${BOARD.h} board; type sizes are board units`,
  "   through --px. Group members are relative to their group (measured off the slide).",
  `   Timing is in fractions of one ${LOOP}s loop; channel windows come from path length at ${SPEED} units/s. */`,
  "",
  "/* artwork */",
  ...Object.entries(TILES).map(([k, [x, y, w, h]]) => `.ufis .k-${k}{left:${px(x)};top:${py(y)};width:${px(w)};height:${py(h)}}`),
  "",
  "/* groups: width and aspect, members inside */",
  ...Object.entries(GROUPS).map(([k, [x, y, w, ar]]) => `.ufis .k-${k}{left:${px(x)};top:${py(y)};width:${px(w)};aspect-ratio:${ar}}`),
  ...kept,
  "",
  "/* text */",
  ...Object.entries(TEXTS).map(([k, [x, y, w, size]]) => `.ufis .k-${k}{left:${px(x)};top:${py(y)};width:${px(w)};font-size:calc(${size} * var(--px))}`),
  "",
  "/* timing: the bead on each channel */",
  ...channels.map((c) => cometFrames(c.id, c.start, c.end)),
  ...channels.map((c) => `.ufis .w-${c.id}{--cm:ufis-cm-${c.id}}`),
  "",
  "/* timing: ripples open when a bead leaves or arrives */",
  ...RIPPLES.map(([, , id, edge], i) => `.ufis .rp-${i}{--at:${edge === "start" ? byId[id].start : byId[id].end}}`),
  "",
  "/* timing: the stage the pulse is inside — panel fill, numeral, pictures */",
  ...Object.entries(FOCUS).map(([k, [a, b]]) =>
    `@keyframes ufis-pool-${k}{0%,${f(a * 100)}%{fill:var(--plate)}${f(a * 100 + 1.2)}%,${f(b * 100)}%{fill:var(--u-pool)}${f(b * 100 + 3)}%,100%{fill:var(--plate)}}`),
  ...Object.entries(FOCUS).map(([k, [a, b]]) =>
    `@keyframes ufis-num-${k}{0%,${f(a * 100)}%{color:var(--ink-mute)}${f(a * 100 + 1.2)}%,${f(b * 100)}%{color:var(--signal)}${f(b * 100 + 3)}%,100%{color:var(--ink-mute)}}`),
  ...Object.entries(FOCUS).map(([k, [a]]) => `.ufis .pn-${k}{--pool:ufis-pool-${k}}\n.ufis .${k} .num{--numk:ufis-num-${k}}\n.ufis .${k}{--at:${f(a + 0.012)}}`),
  "",
];

fs.writeFileSync(out, lines.join("\n"));
console.log(`ufis-coords: wrote ${path.relative(process.cwd(), out)} (${Object.keys(TILES).length} tiles, ${Object.keys(GROUPS).length} groups, ${Object.keys(TEXTS).length} texts, ${channels.length} channels timed)`);
for (const c of channels) console.log(`  ${c.id.padEnd(5)} ${c.len.toFixed(0).padStart(4)}u  ${(c.start * LOOP).toFixed(2)}s → ${(c.end * LOOP).toFixed(2)}s`);
